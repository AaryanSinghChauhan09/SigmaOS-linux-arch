//! archinstall automated setup & guided installation profile engine
//! Direct inspiration: https://github.com/archlinux/archinstall

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ProfileKind {
    Minimal,
    Desktop,
    Server,
    Developer,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum DesktopEnvironment {
    SovereignZenith,
    Cinnamon,
    Gnome,
    KdePlasma,
    Hyprland,
    None,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum FilesystemKind {
    Btrfs,
    Ext4,
    Xfs,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum NetworkManagerType {
    NetworkManager,
    SystemdNetworkd,
    Manual,
}

#[derive(Debug, Clone)]
pub struct SubvolumeConfig {
    pub name: String,
    pub mountpoint: String,
    pub mount_options: String,
}

#[derive(Debug, Clone)]
pub struct ArchinstallProfile {
    pub hostname: String,
    pub profile_kind: ProfileKind,
    pub desktop: DesktopEnvironment,
    pub filesystem: FilesystemKind,
    pub network: NetworkManagerType,
    pub kernel: String,
    pub enable_audio_pipewire: bool,
    pub enable_zram: bool,
    pub disk_device: String,
    pub user_name: String,
    pub user_sudo: bool,
}

impl Default for ArchinstallProfile {
    fn default() -> Self {
        Self {
            hostname: "sigmaos".to_string(),
            profile_kind: ProfileKind::Desktop,
            desktop: DesktopEnvironment::SovereignZenith,
            filesystem: FilesystemKind::Btrfs,
            network: NetworkManagerType::NetworkManager,
            kernel: "sigma-kernel".to_string(),
            enable_audio_pipewire: true,
            enable_zram: true,
            disk_device: "/dev/vda".to_string(),
            user_name: "sigma".to_string(),
            user_sudo: true,
        }
    }
}

impl ArchinstallProfile {
    /// Generate standard Btrfs subvolumes layout per Arch & Omarchy best practices
    pub fn standard_btrfs_subvolumes(&self) -> Vec<SubvolumeConfig> {
        vec![
            SubvolumeConfig {
                name: "@".to_string(),
                mountpoint: "/".to_string(),
                mount_options: "noatime,compress=zstd:1,space_cache=v2".to_string(),
            },
            SubvolumeConfig {
                name: "@home".to_string(),
                mountpoint: "/home".to_string(),
                mount_options: "noatime,compress=zstd:1,space_cache=v2".to_string(),
            },
            SubvolumeConfig {
                name: "@snapshots".to_string(),
                mountpoint: "/.snapshots".to_string(),
                mount_options: "noatime,compress=zstd:1,space_cache=v2".to_string(),
            },
            SubvolumeConfig {
                name: "@var_log".to_string(),
                mountpoint: "/var/log".to_string(),
                mount_options: "noatime,compress=zstd:1,space_cache=v2".to_string(),
            },
        ]
    }

    /// List package requirements for this installation profile
    pub fn required_packages(&self) -> Vec<&'static str> {
        let mut pkgs = vec!["base", "base-devel", "linux-firmware"];

        match self.filesystem {
            FilesystemKind::Btrfs => pkgs.extend_from_slice(&["btrfs-progs", "snapper"]),
            FilesystemKind::Ext4 => pkgs.push("e2fsprogs"),
            FilesystemKind::Xfs => pkgs.push("xfsprogs"),
        }

        match self.network {
            NetworkManagerType::NetworkManager => pkgs.extend_from_slice(&["networkmanager", "iwd"]),
            NetworkManagerType::SystemdNetworkd => pkgs.push("systemd"),
            NetworkManagerType::Manual => {}
        }

        if self.enable_audio_pipewire {
            pkgs.extend_from_slice(&["pipewire", "pipewire-pulse", "wireplumber"]);
        }

        if self.enable_zram {
            pkgs.push("zram-generator");
        }

        match self.desktop {
            DesktopEnvironment::SovereignZenith => pkgs.push("sigmaos-zenith-desktop"),
            DesktopEnvironment::Cinnamon => pkgs.extend_from_slice(&["cinnamon", "nemo", "slick-greeter"]),
            DesktopEnvironment::Gnome => pkgs.extend_from_slice(&["gnome", "gdm"]),
            DesktopEnvironment::KdePlasma => pkgs.extend_from_slice(&["plasma-meta", "sddm"]),
            DesktopEnvironment::Hyprland => pkgs.extend_from_slice(&["hyprland", "waybar", "kitty"]),
            DesktopEnvironment::None => {}
        }

        pkgs
    }

    /// Generate fstab entries for the disk layout
    pub fn generate_fstab(&self, esp_uuid: &str, root_uuid: &str) -> String {
        let mut fstab = String::new();
        fstab.push_str("# /etc/fstab generated by SigmaOS archinstall engine\n");
        fstab.push_str("# <file system> <mount point> <type> <options> <dump> <pass>\n\n");

        // EFI System Partition
        fstab.push_str(&format!(
            "UUID={} /boot/efi      vfat    fmask=0077,dmask=0077 0 2\n",
            esp_uuid
        ));

        match self.filesystem {
            FilesystemKind::Btrfs => {
                for subvol in self.standard_btrfs_subvolumes() {
                    fstab.push_str(&format!(
                        "UUID={} {:<14} btrfs   subvol={},{} 0 0\n",
                        root_uuid, subvol.mountpoint, subvol.name, subvol.mount_options
                    ));
                }
            }
            FilesystemKind::Ext4 => {
                fstab.push_str(&format!(
                    "UUID={} /              ext4    noatime,errors=remount-ro 0 1\n",
                    root_uuid
                ));
            }
            FilesystemKind::Xfs => {
                fstab.push_str(&format!(
                    "UUID={} /              xfs     noatime 0 1\n",
                    root_uuid
                ));
            }
        }

        fstab
    }
}
